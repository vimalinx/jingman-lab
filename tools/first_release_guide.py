class Manual(base.Guide):
    def page(self, title, subtitle, section):
        super().page(title, subtitle, section)
        # Replace the running header, not the screenshot content.
        self.c.setFillColor(base.white)
        self.c.rect(base.M-1, base.H-44, 350, 19, fill=1, stroke=0)
        self.c.setFillColor(base.MUTED)
        self.c.setFont('CN', 9)
        self.c.drawString(base.M, base.H-37, '京漫便民 / R1 内部试用图文手册')

    def footer(self):
        self.c.setStrokeColor(base.LINE)
        self.c.line(base.M,45,base.W-base.M,45)
        self.c.setFont('CN',8)
        self.c.setFillColor(base.MUTED)
        self.c.drawString(base.M,30,'真实商品快照 / 模拟交易 / 仅限已配置的本机内部试用')
        self.c.drawRightString(base.W-base.M,30,f'2026-09-15 / {self.n:02d}')

    def figure(self, name, caption, crop=None, width=None):
        im = ImageReader(ASSETS/name)
        iw, ih = im.getSize()
        cx, cy, cw, ch = crop or (0,0,iw,ih)
        width = width or base.CW
        scale = width/cw
        height = ch*scale
        x = (base.W-width)/2
        bottom = self.y-height
        if bottom < 85:
            raise ValueError(f'Figure overflow: page {self.n}')
        self.c.saveState()
        path = self.c.beginPath()
        path.rect(x,bottom,width,height)
        self.c.clipPath(path,stroke=0)
        self.c.drawImage(im,x-cx*scale,self.y-(ih-cy)*scale,iw*scale,ih*scale)
        self.c.restoreState()
        self.c.setStrokeColor(base.LINE)
        self.c.rect(x,bottom,width,height,stroke=1,fill=0)
        self.y = bottom-8
        self.p(caption,9,base.MUTED,13)


